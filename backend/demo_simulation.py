"""Create versioned, safe demo telemetry for the hosted incident dashboard."""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

STATE_PATH = Path(__file__).with_name("demo_state.json")

INCIDENT_LIBRARY = [
    ("Authentication Service", "OAuth token verification failures", "critical", 500, 3200.0, "Redis session cache timed out during token verification."),
    ("Payment Gateway", "Payment provider upstream timeout", "critical", 504, 5800.0, "The simulated payment provider did not respond before the health-check timeout."),
    ("Catalog Search API", "Search cluster high memory and latency", "high", 503, 2900.0, "Search requests are slow while the simulated cluster is under memory pressure."),
    ("Notification Service", "Email delivery failures", "high", 500, 1150.0, "The simulated SMTP relay rejected outbound notification requests."),
    ("Inventory Management", "Database replica lag", "high", 500, 6100.0, "Inventory reads are delayed by simulated database replica lag."),
    ("API Gateway", "Rate limiter policy misconfiguration", "critical", 429, 45.0, "The simulated gateway is applying a restrictive global rate limit."),
    ("Content Delivery Network", "CDN edge cache propagation failure", "high", 502, 870.0, "The simulated origin shield is failing to serve fresh assets."),
    ("Order Processing Service", "Queue consumer lag exceeded threshold", "critical", 503, 7400.0, "The simulated order queue is backing up while consumers are unavailable."),
    ("User Profile Service", "Document store connection pool saturated", "medium", 500, 4200.0, "The simulated profile store has exhausted its connection pool."),
    ("Shipping Logistics Service", "Carrier webhook delivery failures", "medium", 502, 3100.0, "The simulated carrier endpoint is rejecting tracking webhooks."),
]


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def read_state() -> dict[str, Any]:
    if not STATE_PATH.exists():
        return {"mode": "healthy", "updatedAt": None, "nextIndex": 0, "incidents": [], "checks": [], "services": []}
    return json.loads(STATE_PATH.read_text(encoding="utf-8"))


def write_state(state: dict[str, Any]) -> None:
    state["updatedAt"] = now_iso()
    serialized = json.dumps(state, indent=2)
    STATE_PATH.write_text(serialized + "\n", encoding="utf-8")
    snapshot_module = STATE_PATH.with_name("demo_snapshot.py")
    snapshot_module.write_text(
        '"""Build-time copy of demo_state.json, regenerated by simulate_incidents.py."""\n\n'
        f"SNAPSHOT_JSON = {json.dumps(json.dumps(state, separators=(',', ':')))}\n",
        encoding="utf-8",
    )


def _service_state(state: dict[str, Any], name: str) -> dict[str, Any]:
    for service in state["services"]:
        if service["service"] == name:
            return service
    service = {"service": name, "consecutiveFailures": 0, "lastStatus": "unknown", "activeIncidentId": None}
    state["services"].append(service)
    return service


def _record_check(state: dict[str, Any], service: str, incident_id: str | None, healthy: bool, observed_at: str, http_status: int, latency: float, error: str = "") -> None:
    state["checks"].append({
        "service": service,
        "incidentId": incident_id,
        "observedAt": observed_at,
        "healthy": healthy,
        "httpStatus": http_status,
        "responseTimeMs": latency,
        "failureKind": None if healthy else "http_failure",
        "errorDetails": error,
    })


def resolve_active(state: dict[str, Any], observed_at: str | None = None) -> int:
    observed_at = observed_at or now_iso()
    resolved = 0
    for incident in state["incidents"]:
        if incident["status"] != "active":
            continue
        incident["status"] = "resolved"
        incident["lastObserved"] = observed_at
        incident["resolvedAt"] = observed_at
        incident["lastHttpStatus"] = 200
        incident["lastResponseTimeMs"] = 42.0
        incident["errorDetails"] = ""
        incident["events"].append({
            "eventType": "resolved",
            "observedAt": observed_at,
            "summary": "Demo command reported that the service recovered.",
            "httpStatus": 200,
            "responseTimeMs": 42.0,
            "errorDetails": "",
        })
        service = _service_state(state, incident["service"])
        service.update({"consecutiveFailures": 0, "lastStatus": "healthy", "activeIncidentId": None})
        _record_check(state, incident["service"], incident["id"], True, observed_at, 200, 42.0)
        resolved += 1
    state["mode"] = "healthy"
    return resolved


def set_healthy() -> int:
    state = read_state()
    resolved = resolve_active(state)
    if not state["services"]:
        service = _service_state(state, "Target application")
        service.update({"consecutiveFailures": 0, "lastStatus": "healthy", "activeIncidentId": None})
        _record_check(state, "Target application", None, True, now_iso(), 200, 42.0)
    write_state(state)
    return resolved


def trigger_incidents(count: int, *, replace_active: bool = False) -> list[dict[str, Any]]:
    if not 1 <= count <= len(INCIDENT_LIBRARY):
        raise ValueError(f"count must be between 1 and {len(INCIDENT_LIBRARY)}")
    state = read_state()
    if replace_active:
        resolve_active(state)

    active_services = {item["service"] for item in state["incidents"] if item["status"] == "active"}
    start = int(state.get("nextIndex", 0)) % len(INCIDENT_LIBRARY)
    available = [
        (start + offset) % len(INCIDENT_LIBRARY)
        for offset in range(len(INCIDENT_LIBRARY))
        if INCIDENT_LIBRARY[(start + offset) % len(INCIDENT_LIBRARY)][0] not in active_services
    ]
    if len(available) < count:
        raise ValueError("Too many active demo services. Run 'python simulate_incidents.py health' before triggering more.")

    created = []
    now = datetime.now(timezone.utc)
    for offset, library_index in enumerate(available[:count]):
        service, title, severity, http_status, latency, details = INCIDENT_LIBRARY[library_index]
        observed_at = (now + timedelta(microseconds=offset)).isoformat()
        incident_id = f"inc-demo-{uuid.uuid4().hex[:12]}"
        incident = {
            "id": incident_id,
            "title": title,
            "summary": details,
            "service": service,
            "severity": severity,
            "status": "active",
            "firstDetected": observed_at,
            "lastObserved": observed_at,
            "resolvedAt": None,
            "lastHttpStatus": http_status,
            "lastResponseTimeMs": latency,
            "errorDetails": details,
            "events": [
                {"eventType": "opened", "observedAt": observed_at, "summary": f"Incident opened after three simulated failing checks for {service}.", "httpStatus": http_status, "responseTimeMs": latency, "errorDetails": details},
                {"eventType": "failure_observed", "observedAt": observed_at, "summary": f"Demo mode reported HTTP {http_status} ({latency:g} ms).", "httpStatus": http_status, "responseTimeMs": latency, "errorDetails": details},
            ],
        }
        state["incidents"].append(incident)
        service_state = _service_state(state, service)
        service_state.update({"consecutiveFailures": 3, "lastStatus": "failing", "activeIncidentId": incident_id})
        for check_number in range(3):
            check_time = (now + timedelta(seconds=check_number, microseconds=offset)).isoformat()
            _record_check(state, service, incident_id, False, check_time, http_status, latency, details)
        created.append(incident)

    state["nextIndex"] = (available[count - 1] + 1) % len(INCIDENT_LIBRARY)
    state["mode"] = "failure"
    write_state(state)
    return created


def reset() -> None:
    write_state({"mode": "unknown", "nextIndex": 0, "incidents": [], "checks": [], "services": []})
